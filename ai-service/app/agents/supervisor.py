"""Supervisor agent node for dynamic intent classification and loop-bounded routing."""

import logging
import re
from typing import Any

from app.agents.state import AgentState, RouteOption
from app.services.llm import call_gemini_api

logger = logging.getLogger(__name__)

MAX_SUPERVISOR_ITERATIONS = 3

SUPERVISOR_SYSTEM_PROMPT = """You are the WorkMesh AI Multi-Agent Supervisor Router for WorkMesh Technologies Pvt. Ltd.
Your job is to analyze the user's input, context, and current execution trajectory, and decide which specialized agent node should act next.

Available Worker Nodes:
1. "knowledge_agent": Use when the user asks factual, policy, procedural, technical, handbook, or company documentation questions that require searching enterprise documents via semantic retrieval.
2. "office_agent": Use when the user requests drafting, composing, writing communications, creating meeting summaries, formatting announcements, extracting action items, or structuring office memos.
3. "FINISH": Use when:
   - A complete response has already been generated by one of the workers.
   - The query is a simple conversational greeting, farewell, or pleasantry requiring no document retrieval or document drafting.
   - The request cannot be handled by available agents.

Response Format:
Respond ONLY with one of the three options:
knowledge_agent
office_agent
FINISH

Do not include any explanation, punctuation, or extra words.
"""


def parse_supervisor_route(llm_output: str) -> RouteOption:
    """Safely extract the chosen route from raw model output."""
    cleaned = llm_output.strip().lower()

    if "knowledge_agent" in cleaned or "knowledge" in cleaned or "search" in cleaned:
        return "knowledge_agent"
    if "office_agent" in cleaned or "office" in cleaned or "draft" in cleaned:
        return "office_agent"
    if "finish" in cleaned:
        return "FINISH"

    # Default fallback: If query involves asking a question, default to knowledge retrieval
    return "knowledge_agent"


def supervisor_node(state: AgentState) -> dict[str, Any]:
    """Execute supervisor routing logic with cycle bounding and intent classification."""
    iteration = state.get("iteration_count", 0)
    agent_path = list(state.get("agent_path", []))
    agent_path.append("supervisor")

    # Cycle Limit Guardrail: Prevent unbounded execution loops
    if iteration >= MAX_SUPERVISOR_ITERATIONS:
        logger.warning(
            "Supervisor reached maximum iteration limit (%d). Forcing FINISH.",
            MAX_SUPERVISOR_ITERATIONS,
        )
        fallback_msg = (
            state.get("final_response")
            or "I have processed your request to the maximum allowable steps. Please let me know if you need more details."
        )
        return {
            "current_agent": "supervisor",
            "route": "FINISH",
            "iteration_count": iteration + 1,
            "agent_path": agent_path,
            "final_response": fallback_msg,
        }

    # If an answer has already been synthesized by a worker, finish
    if state.get("final_response"):
        return {
            "current_agent": "supervisor",
            "route": "FINISH",
            "iteration_count": iteration + 1,
            "agent_path": agent_path,
        }

    query = state.get("query", "").strip()

    # Fast-path for empty or greeting queries
    greeting_pattern = re.compile(
        r"^(hi|hello|hey|good morning|good afternoon|good evening|greetings)\b",
        re.IGNORECASE,
    )
    if not query:
        return {
            "current_agent": "supervisor",
            "route": "FINISH",
            "iteration_count": iteration + 1,
            "agent_path": agent_path,
            "final_response": "How can I assist you with WorkMesh company knowledge or office tasks today?",
        }

    if greeting_pattern.match(query) and len(query.split()) <= 4:
        return {
            "current_agent": "supervisor",
            "route": "FINISH",
            "iteration_count": iteration + 1,
            "agent_path": agent_path,
            "final_response": "Hello! I am your WorkMesh AI Assistant. I can help search company policies, answer questions from documents, or draft office communications. How can I help you?",
        }

    # Invoke Gemini router
    user_prompt = f"User Request: {query}\nIteration: {iteration}"
    try:
        raw_decision = call_gemini_api(
            system_prompt=SUPERVISOR_SYSTEM_PROMPT,
            user_prompt=user_prompt,
        )
        chosen_route = parse_supervisor_route(raw_decision)
    except Exception as exc:  # noqa: BLE001
        logger.error("Supervisor routing error: %s. Defaulting to knowledge_agent", exc)
        chosen_route = "knowledge_agent"

    logger.info("Supervisor decided next route: %s for query: %s", chosen_route, query[:50])

    return {
        "current_agent": "supervisor",
        "route": chosen_route,
        "iteration_count": iteration + 1,
        "agent_path": agent_path,
    }
